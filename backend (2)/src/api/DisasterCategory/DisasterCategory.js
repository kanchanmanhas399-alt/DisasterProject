const mongoose = require('mongoose');

const disasterCategorySchema = new mongoose.Schema({
  name: {
    type: String,
    required: true,
    unique: true,
    trim: true
  },
  description: {
    type: String,
    required: true
  },
  imageIcon: {
    type: String, // URL or file path for the icon/image
    required: true
  },
  status: {
    type: String,
    enum: ['active', 'inactive'],
    default: 'active'
  }
}, {
  timestamps: true
});

module.exports = mongoose.model('DisasterCategory', disasterCategorySchema);